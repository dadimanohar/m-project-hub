<h2 class="wp-block-heading" id="pipeline">The retrieval pipeline in plain terms</h2>
<!-- /wp:heading -->
<!-- wp:list {"ordered":true} -->
<ol class="wp-block-list"><li><strong>Fetch</strong> — A crawler requests your URL. If robots.txt blocks it or the content needs JavaScript, the pipeline stops here.</li><li><strong>Parse</strong> — HTML is stripped to text and structure. Semantic headings and tables survive; visual-only layout does not.</li><li><strong>Chunk</strong> — Content is split into passages, usually at heading or paragraph boundaries.</li><li><strong>Embed and index</strong> — Each chunk becomes a vector stored for similarity search.</li><li><strong>Retrieve and generate</strong> — The query matches chunks, and the model writes an answer from the top matches, citing their sources.</li></ol>
<!-- /wp:list -->
<!-- wp:paragraph -->
<p>Every optimisation we make targets a specific stage of this pipeline. That is what separates retrieval engineering from generic \'write good content\' advice.</p>
