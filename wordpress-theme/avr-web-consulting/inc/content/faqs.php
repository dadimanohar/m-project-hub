<h2 class="wp-block-heading">AI SEO (90)</h2>
<!-- /wp:heading -->
<!-- wp:details -->
<details class="wp-block-details"><summary>What is AI SEO?</summary><!-- wp:paragraph -->
<p>AI SEO is optimisation for AI-powered answer engines. It makes your content retrievable, quotable and attributable so assistants such as ChatGPT, Gemini, Perplexity, Copilot and Google AI Overviews name your brand when answering relevant questions.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>Is AI SEO different from traditional SEO?</summary><!-- wp:paragraph -->
<p>It overlaps but is not identical. Traditional SEO competes for ranked links; AI SEO competes for inclusion inside a synthesised answer. Content format, entity consistency and structured data matter more, and success is measured in citations rather than positions.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>Does AI SEO replace normal SEO?</summary><!-- wp:paragraph -->
<p>No. Most assistants retrieve from live search results, so poor crawlability or weak authority still blocks you. AI SEO is a layer on top of technically sound, authoritative SEO.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>How do you measure AI visibility?</summary><!-- wp:paragraph -->
<p>We maintain a prompt set of real buyer questions and run it monthly across the major assistants, recording whether your brand is mentioned, cited with a link, described accurately, and how that compares to competitors.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>How long does AI SEO take to show results?</summary><!-- wp:paragraph -->
<p>Retrieval improvements from structured data and content reformatting can appear within 2–6 weeks. Entity and authority work — the part that makes models recommend you unprompted — typically takes three to six months.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>Can you control what an AI says about my brand?</summary><!-- wp:paragraph -->
<p>You cannot control it directly, but you can strongly influence it by publishing clear, consistent, well-structured facts about your business and getting those facts repeated on sources the models trust.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>Should I block AI crawlers?</summary><!-- wp:paragraph -->
<p>If you want AI visibility, no. Blocking GPTBot, ClaudeBot, PerplexityBot or Google-Extended removes you from those systems. We configure robots.txt deliberately so you allow the engines you want to appear in.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>What is llms.txt?</summary><!-- wp:paragraph -->
<p>llms.txt is a plain-text file at the root of a site that summarises what the site offers and links to key pages in a machine-friendly way. It is an emerging convention we implement as part of LLMO work.</p>
<!-- /wp:paragraph --></details>
