<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>What is content chunking?</summary><!-- wp:paragraph -->
<p>Retrieval systems split pages into passages, embed them and match them to queries. Chunking-friendly content uses clear headings and self-contained sections so each passage remains meaningful on its own.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>Do I need llms.txt?</summary><!-- wp:paragraph -->
<p>It is optional and still an emerging convention, but it is cheap to add and gives LLM consumers a clean summary of your site and its key URLs. We include it in every LLMO engagement.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>Does JavaScript hurt LLM retrieval?</summary><!-- wp:paragraph -->
<p>It can. Several AI crawlers do not execute JavaScript, so content that only appears after hydration is invisible to them. Server-side rendering solves this.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>Which schema types matter most for LLMO?</summary><!-- wp:paragraph -->
<p>Organization and WebSite for identity, Service for offerings, Article for editorial content, FAQPage for question-answer pairs, LocalBusiness for physical presence and BreadcrumbList for context.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>Should PDFs be converted to HTML?</summary><!-- wp:paragraph -->
<p>Usually yes. Key facts locked inside PDFs, images or embedded tools are far less reliably retrieved than the same information in HTML.</p>
<!-- /wp:paragraph --></details>
