<h2 class="wp-block-heading" id="faqs">Frequently asked questions</h2>
<!-- /wp:heading -->
<!-- wp:details -->
<details class="wp-block-details"><summary>How much does a guest post cost?</summary><!-- wp:paragraph -->
<p>Placements start at $20 on smaller niche blogs and rise with the host site\'s traffic and authority — mid-tier industry publications typically run $60–$150. You see the site, metrics and price before we commit to anything.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>Is guest posting still effective in 2026?</summary><!-- wp:paragraph -->
<p>Yes, when the placement is genuinely editorial on a site people actually read. What no longer works is mass-published filler on link farms, which search engines discount and AI models ignore as a credibility signal.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>Are your links safe from Google penalties?</summary><!-- wp:paragraph -->
<p>We build the way a PR team would: relevant sites, natural anchor text distribution, gradual pace and no networks. Clients have not experienced manual actions from our placements, and every link is disclosed to you.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>How many links do I need per month?</summary><!-- wp:paragraph -->
<p>Most competitive campaigns run four to ten quality placements a month. The right number depends on competitor link velocity in your niche, which we measure in the audit rather than guess.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>Do you use PBNs?</summary><!-- wp:paragraph -->
<p>Never. Private blog networks are the single fastest route to a manual action, and their footprints are increasingly easy to detect. Every site we place on is an independent publication.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>How long until links affect rankings?</summary><!-- wp:paragraph -->
<p>Links usually take four to twelve weeks to show measurable ranking impact, as the pages need to be crawled, evaluated and trusted. Competitive terms need consistent link acquisition over several months, not a single burst.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>Do you write the guest post content?</summary><!-- wp:paragraph -->
<p>Yes. Our writers produce the article to the host publication\'s editorial standards, with the link placed contextually. You approve the topic and can review the draft before submission.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>Can I choose the anchor text?</summary><!-- wp:paragraph -->
<p>You can specify preferences, and we will advise on distribution. Over-optimised exact-match anchors are one of the clearest spam signals, so we keep branded and natural-phrase anchors as the majority.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>Do links help AI visibility?</summary><!-- wp:paragraph -->
<p>Yes, indirectly but importantly. Language models weigh how often and how credibly a brand is mentioned across the web. Editorial placements create the corroborating sources that make an assistant comfortable recommending you by name.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>What reporting do I receive?</summary><!-- wp:paragraph -->
<p>A live sheet listing every placement: host site, live URL, publication date, organic traffic estimate, authority metrics, anchor text and destination page — updated as each link goes live, not summarised at the end of the month.</p>
